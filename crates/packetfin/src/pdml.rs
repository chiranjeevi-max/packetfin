fn malformed_expert(node: &Node) -> Option<&packetfin_core::tree::ExpertInfo> {
    if !node.protocol_exception {
        return None;
    }
    node.experts
        .iter()
        .find(|expert| expert.group == packetfin_core::Group::Malformed)
}

fn malformed_message(expert: &packetfin_core::tree::ExpertInfo) -> &str {
    if expert.message.contains("truncated")
        || expert.message.contains("is empty")
        || expert.message.contains("shorter than")
    {
        "Malformed Packet (Exception occurred)"
    } else {
        &expert.message
    }
}

/// Offset for a protocol-exception marker: the first protocol
/// below the link layer (or the link layer for non-Ethernet captures).
fn malformed_anchor(packet: &Packet) -> usize {
    let frame = &packet.tree.frame;
    let Some(link) = frame.children.first() else {
        return 0;
    };
    if link.protocol.filter_name == "eth" {
        link.children
            .first()
            .map_or(link.range.offset, |child| child.range.offset)
    } else {
        link.range.offset
    }
}

