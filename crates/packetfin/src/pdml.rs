fn dns_flags_summary(flags: u64) -> String {
    let opcode = (flags >> 11) & 0x0f;
    let response = flags & 0x8000 != 0;
    let rcode = flags & 0x0f;
    let mut text = dns_opcode_name(opcode).to_string();
    if response {
        text.push_str(" response, ");
        text.push_str(dns_rcode_name(rcode));
    }
    text
}

