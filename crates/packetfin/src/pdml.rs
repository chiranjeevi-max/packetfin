/// ISO 8601 date and time with nine fractional digits and the given suffix.
fn iso_time(timestamp: Timestamp, suffix: &str) -> String {
    let (year, month, day, hour, minute, second) = civil_time(timestamp.seconds);
    format!(
        "{year:04}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}.{:09}{suffix}",
        timestamp.nanos
    )
}

/// The root `time` attribute: ctime format in local time.
fn local_time() -> String {
    const DAYS: [&str; 7] = ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"];
    const MONTHS: [&str; 12] = [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ];
    let seconds = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|duration| i64::try_from(duration.as_secs()).unwrap_or(0))
        .unwrap_or(0);
    let days = seconds.div_euclid(86_400);
    let weekday = usize::try_from((days + 4).rem_euclid(7)).unwrap_or(0);
    let (year, month, day, hour, minute, second) = civil_time(seconds);
    let day_name = DAYS.get(weekday).copied().unwrap_or("Sun");
    let month_name = MONTHS
        .get(usize::try_from(month).unwrap_or(1).saturating_sub(1))
        .copied()
        .unwrap_or("Jan");
    format!("{day_name} {month_name} {day:>2} {hour:02}:{minute:02}:{second:02} {year:04}")
}

